/** The bound a Guide visit reads at, with the label shown for it. */
export interface GuideBound {
	choice: GuideBoundChoice;
	/** The unit's label; null for the whole book. */
	label: string | null;
}

/**
 * The Guide's default bound: the reading position. A position that no longer
 * ends a current unit falls back to the last unit ending at or before it, so
 * the default never shows more than the position covers. Null when the
 * position is unset or precedes every unit: the reader is asked instead.
 */
export function positionBound(
	position: ReadingPosition | null,
	units: ReadingUnit[],
): GuideBound | null {
	if (position === null) return null;
	if (position.kind === "finished")
		return { choice: { kind: "whole" }, label: null };
	const unit = units
		.filter((u) => u.endPosition <= position.maxPosition)
		.at(-1);
	if (!unit) return null;
	return {
		choice: { kind: "unit", endPosition: unit.endPosition },
		label: unit.label,
	};
}

/** Orders bounds: the whole book is past every unit. */
export const boundEnd = (choice: GuideBoundChoice) =>
	choice.kind === "whole" ? Number.POSITIVE_INFINITY : choice.endPosition;

/** A stable query-key part for a bound. */
export const boundKey = (bound: GuideBound) =>
	bound.choice.kind === "whole" ? "whole" : bound.choice.endPosition;

export interface GuideContextValue {
	editionId: string;
	/** Null until the reader has a position or chooses a bound. */
	bound: GuideBound | null;
	/** Whether the book has any current preprocessing. */
	preprocessed: boolean;
	/** Called when the server rejects the bound because the book's units changed. */
	onStaleBound: () => void;
}

export const GuideContext = createContext<GuideContextValue | null>(null);

/** The visit's Guide state, from the layout route. */
export function useGuide(): GuideContextValue {
	const value = useContext(GuideContext);
	if (!value) throw new Error("useGuide must be used inside the Guide layout");
	return value;
}

/** A derived item's citations: each links to its passage, unverified ones are marked. */
export function GuideCitations({
	citations,
}: {
	citations: DerivedCitation[];
}) {
	if (citations.length === 0) return null;
	return (
		<ul className="mt-2 space-y-1 text-sm">
			{citations.map((c, i) => (
				<li
					// Quotes may repeat; their order is fixed.
					// biome-ignore lint/suspicious/noArrayIndexKey: citations are a fixed list
					key={i}
					className="flex flex-wrap items-baseline gap-2"
					data-citation-status={c.verified ? "verified" : "unverified"}
				>
					<Link
						to="/p/$locator"
						params={{ locator: c.locator }}
						className="text-muted-foreground italic underline-offset-2 hover:underline"
					>
						“{c.quote}”
					</Link>
					{!c.verified && (
						<Badge
							variant="outline"
							title="This quote could not be confirmed in the book's text."
						>
							Unverified
						</Badge>
					)}
				</li>
			))}
		</ul>
	);
}

const STATES: Record<GuideProvenance["state"], string> = {
	current: "up to date",
	partial: "some chapters are not summarized yet",
	stale: "out of date: the book changed or the prompt was updated since",
};

/** "Generated by M · prompt version 2 · up to date". */
export function provenanceText(p: GuideProvenance): string {
	const parts = [
		p.models.length > 0 ? `Generated by ${p.models.join(", ")}` : null,
		p.promptVersions.length > 0
			? `prompt version ${p.promptVersions.join(", ")}`
			: null,
		STATES[p.state],
	].filter((part) => part !== null);
	const text = parts.join(" · ");
	return text.charAt(0).toUpperCase() + text.slice(1);
}

