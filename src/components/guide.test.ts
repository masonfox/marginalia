// @vitest-environment jsdom
import { createElement, type ReactNode } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it, vi } from "vitest";
import type { ReadingUnit } from "#/modules/catalog";
import { GuideCitations, positionBound, provenanceText } from "./guide";

vi.mock("@tanstack/react-router", () => ({
	Link: ({
		params,
		children,
		className,
	}: {
		params: { locator: string };
		children: ReactNode;
		className?: string;
	}) =>
		createElement("a", { href: `/p/${params.locator}`, className }, children),
}));

const unit = (ordinal: number, start: number, end: number): ReadingUnit => ({
	ordinal,
	label: `Chapter ${ordinal + 1}`,
	path: [`Chapter ${ordinal + 1}`],
	startPosition: start,
	endPosition: end,
	startLocator: `aaaaaaaaaaaa:v1:${ordinal}.0`,
});
const units = [unit(0, 0, 9), unit(1, 10, 19), unit(2, 20, 29)];

describe("GuideCitations", () => {
	it("links every citation to its passage and marks only unverified ones", () => {
		const html = renderToStaticMarkup(
			createElement(GuideCitations, {
				citations: [
					{
						locator: "aaaaaaaaaaaa:v1:0.3",
						quote: "Happy families",
						verified: true,
					},
					{
						locator: "aaaaaaaaaaaa:v1:1.2",
						quote: "All was confusion",
						verified: false,
					},
				],
			}),
		);
		const doc = new DOMParser().parseFromString(html, "text/html");
		const items = [...doc.querySelectorAll("li")];
		expect(items.map((li) => li.dataset.citationStatus)).toEqual([
			"verified",
			"unverified",
		]);
		expect(
			items.map((li) => li.querySelector("a")?.getAttribute("href")),
		).toEqual(["/p/aaaaaaaaaaaa:v1:0.3", "/p/aaaaaaaaaaaa:v1:1.2"]);
		expect(items[0]?.textContent).not.toContain("Unverified");
		expect(items[1]?.textContent).toContain("“All was confusion”");
		expect(items[1]?.textContent).toContain("Unverified");
	});

	it("renders nothing without citations", () => {
		expect(
			renderToStaticMarkup(createElement(GuideCitations, { citations: [] })),
		).toBe("");
	});
});

describe("positionBound", () => {
	it("defaults to the reading position", () => {
		expect(positionBound(null, units)).toBeNull();
		expect(positionBound({ kind: "finished" }, units)).toEqual({
			choice: { kind: "whole" },
			label: null,
		});
		expect(
			positionBound(
				{ kind: "unit", maxPosition: 19, scopeLabel: "Chapter 2" },
				units,
			),
		).toEqual({
			choice: { kind: "unit", endPosition: 19 },
			label: "Chapter 2",
		});
	});

	it("never shows past a position that no longer ends a unit", () => {
		expect(
			positionBound(
				{ kind: "unit", maxPosition: 25, scopeLabel: "Chapter 3" },
				units,
			),
		).toEqual({
			choice: { kind: "unit", endPosition: 19 },
			label: "Chapter 2",
		});
		// Before the first unit ends: ask instead.
		expect(
			positionBound({ kind: "unit", maxPosition: 5, scopeLabel: "x" }, units),
		).toBeNull();
	});
});

describe("provenanceText", () => {
	it("states the model, prompt version and state", () => {
		expect(
			provenanceText({ models: ["M"], promptVersions: [2], state: "current" }),
		).toBe("Generated by M · prompt version 2 · up to date");
		expect(
			provenanceText({ models: [], promptVersions: [], state: "partial" }),
		).toBe("Some chapters are not summarized yet");
	});
});
